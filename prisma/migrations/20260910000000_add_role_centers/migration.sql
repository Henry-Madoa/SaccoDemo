-- Role Centres + Profiles — a Business Central port.
--
-- A "Profile" is a landing-page selector: it decides which Role Centre (tailored home dashboard)
-- a user sees, and NOTHING else. It grants no permissions — the existing Permission Set system
-- (role + permission_set_line) is untouched and fully independent. An admin assigns one or more
-- Profiles to a user; the user switches the active one from My Settings.

-- ============================================================================= profile catalogue

CREATE TABLE "profile" (
    "id"          SERIAL NOT NULL,
    "code"        TEXT   NOT NULL,
    "name"        TEXT   NOT NULL,
    "description" TEXT   NOT NULL DEFAULT '',
    -- The Role Centre this profile lands on. Equals `code` for the six seeded profiles; a
    -- separate column so an admin-added profile can reuse an existing centre.
    "role_centre" TEXT   NOT NULL DEFAULT 'SUPER',
    "icon"        TEXT   NOT NULL DEFAULT '',
    "sort"        INTEGER NOT NULL DEFAULT 0,
    -- The fallback centre when a user has profiles assigned but no active one chosen.
    "is_default"  INTEGER NOT NULL DEFAULT 0,
    -- Seeded rows are system profiles: their code + role_centre are locked in the admin UI.
    "is_system"   INTEGER NOT NULL DEFAULT 0,
    "created_at"  TEXT,
    "created_by"  TEXT,

    CONSTRAINT "profile_pkey" PRIMARY KEY ("id")
);
CREATE UNIQUE INDEX "profile_code_key" ON "profile"("code");

CREATE TABLE "user_profile" (
    "id"         SERIAL NOT NULL,
    "user_id"    INTEGER NOT NULL,
    "profile_id" INTEGER NOT NULL,

    CONSTRAINT "user_profile_pkey" PRIMARY KEY ("id")
);
CREATE UNIQUE INDEX "user_profile_user_id_profile_id_key" ON "user_profile"("user_id", "profile_id");
CREATE INDEX "ix_user_profile_user" ON "user_profile"("user_id");
ALTER TABLE "user_profile" ADD CONSTRAINT "user_profile_user_id_fkey"
    FOREIGN KEY ("user_id") REFERENCES "app_user"("id") ON DELETE CASCADE ON UPDATE NO ACTION;
ALTER TABLE "user_profile" ADD CONSTRAINT "user_profile_profile_id_fkey"
    FOREIGN KEY ("profile_id") REFERENCES "profile"("id") ON DELETE CASCADE ON UPDATE NO ACTION;

ALTER TABLE "app_user" ADD COLUMN "active_profile_id" INTEGER;
ALTER TABLE "app_user" ADD CONSTRAINT "app_user_active_profile_id_fkey"
    FOREIGN KEY ("active_profile_id") REFERENCES "profile"("id") ON DELETE SET NULL ON UPDATE NO ACTION;

