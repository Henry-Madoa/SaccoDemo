-- ============================================================================= backfill existing users
-- Every existing user gets the Super profile and lands on it, so the app behaves exactly as before
-- until an admin assigns more. Guarded on an existing organisation so a fresh DB is seeded by
-- lib/seed.ts instead.

INSERT INTO "user_profile" ("user_id", "profile_id")
SELECT u.id, p.id
FROM "app_user" u
CROSS JOIN "profile" p
WHERE p.code = 'SUPER'
  AND EXISTS (SELECT 1 FROM "organisation")
  AND NOT EXISTS (SELECT 1 FROM "user_profile" up WHERE up.user_id = u.id AND up.profile_id = p.id);

UPDATE "app_user"
SET "active_profile_id" = (SELECT id FROM "profile" WHERE code = 'SUPER')
WHERE "active_profile_id" IS NULL
  AND EXISTS (SELECT 1 FROM "organisation");

