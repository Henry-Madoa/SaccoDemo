-- A finance module was one page, so a permission set could open all of Receivables or none of
-- it: there was no "Sales Invoices" page to grant Execute on. Each module tab is now a page of
-- its own, a child of the module page. Every permission set (and per-user line) that could open
-- a module keeps opening all of it: its children are granted here, and the admin takes screens
-- away from there.
INSERT INTO "permission_set_line"
  ("role_id", "object_type", "object_name", "read_perm", "insert_perm", "modify_perm", "delete_perm", "execute_perm")
SELECT l."role_id", 'PAGE', c.code, 0, 0, 0, 0, 1
FROM "permission_set_line" l
JOIN (VALUES
  ('GL', 'GL_TRIAL_BALANCE'),
